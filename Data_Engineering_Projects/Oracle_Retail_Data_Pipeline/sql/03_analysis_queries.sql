-- Q18. Discounted Sales
-- Find order items where the actual selling price (ORDER_ITEMS.UNIT_PRICE) was lower than the
-- listed product price (PRODUCTS.PRICE).
-- Display:
--   order ID
--   product name
--   listed price
--   selling price
--   discount amount per unit
SELECT oi.order_id AS "Order ID",
       pd.product_name AS "Product Name",
       pd.price AS "Listed Price",
       oi.unit_price AS "Selling Price",
       pd.price - oi.unit_price AS "Discount Amount Per Unit"
  FROM products pd
      JOIN order_items oi
        ON oi.product_id = pd.product_id
 WHERE oi.unit_price < pd.price;


-- Q19. Revenue by State
-- Calculate total revenue generated by customers in each state.
-- Only completed orders should be included.
-- Display the state and total revenue.
-- Sort the results from highest revenue to lowest.
SELECT cs.state AS "State",
       SUM(oi.quantity * oi.unit_price) AS "Total Revenue"
  FROM customers cs
      JOIN orders od
        ON od.customer_id = cs.customer_id
      JOIN order_items oi
        ON oi.order_id = od.order_id
 WHERE od.status = 'COMPLETED'
GROUP BY cs.state
ORDER BY SUM(oi.quantity * oi.unit_price) DESC;


-- Q20. Top Customer in Each State
-- Find the customer with the highest total spending in each state using completed orders only.
-- Display:
--   state
--   customer ID
--   customer name
--   total spending
WITH state_rev AS (
    SELECT pre_pr.*,
           ROW_NUMBER() OVER (PARTITION BY pre_pr.state ORDER BY pre_pr.rev DESC) rn
      FROM (
            SELECT cs.state,
                   cs.customer_id,
                   cs.customer_name,
                   SUM( oi.quantity * oi.unit_price ) rev
              FROM customers cs
                    JOIN orders od
                      ON od.customer_id = cs.customer_id
                    JOIN order_items oi
                      ON oi.order_id = od.order_id
             WHERE od.status = 'COMPLETED'
            GROUP BY cs.state, cs.customer_id, cs.customer_name
           ) pre_pr
)
SELECT state AS "state",
       customer_id AS "customer ID",
       customer_name AS "customer name",
       rev as "total spending"
  FROM state_rev 
WHERE rn = 1;