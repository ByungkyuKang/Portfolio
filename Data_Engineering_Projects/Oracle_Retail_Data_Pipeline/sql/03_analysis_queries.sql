-- Q15. Product Revenue Ranking
-- Rank all products based on their total revenue from completed orders.
-- Display the product name, category, total revenue, and revenue rank.
SELECT pd.product_name,
       pd.category,
       SUM(oi.quantity * oi.unit_price) AS total_revenue,
       RANK() OVER (
           ORDER BY SUM(oi.quantity * oi.unit_price) DESC
       ) AS revenue_rank
  FROM products pd
      JOIN order_items oi
        ON pd.product_id = oi.product_id
      JOIN orders od
        ON oi.order_id = od.order_id
 WHERE od.status = 'COMPLETED'
 GROUP BY pd.product_name, pd.category
 ORDER BY revenue_rank;


-- Q16. Product Ranking Within Each Category
-- Rank products by total revenue within their own product category using completed orders only.
-- Display the category, product name, total revenue, and rank within the category.
WITH grouped_by_category AS (
    SELECT pd.category,
           pd.product_name,
           SUM(oi.quantity * oi.unit_price) AS rev
      FROM products pd
          JOIN order_items oi
            ON pd.product_id = oi.product_id
          JOIN orders od
            ON oi.order_id = od.order_id
     WHERE od.status = 'COMPLETED'
     GROUP BY pd.category,
              pd.product_name
)
SELECT gc.category,
       gc.product_name,
       gc.rev AS total_revenue,
       RANK() OVER ( PARTITION BY gc.category
                     ORDER BY gc.rev DESC
                   ) AS "Rank By Category"
  FROM grouped_by_category gc
ORDER BY gc.category, "Rank By Category";


-- Q17. Previous Month Revenue Comparison
-- Calculate monthly revenue using completed orders.
-- Compare each month's revenue with the previous month's revenue.
-- Display:
--   year-month
--   current month revenue
--   previous month revenue
--   revenue difference
WITH monthly_revenue AS (
    SELECT
        TO_CHAR(od.order_date, 'YYYY-MM') AS year_month,
        SUM(oi.quantity * oi.unit_price) AS current_revenue
    FROM orders od
        JOIN order_items oi
          ON od.order_id = oi.order_id
    WHERE od.status = 'COMPLETED'
    GROUP BY TO_CHAR(od.order_date, 'YYYY-MM')
)
SELECT
    year_month,
    current_revenue,
    LAG(current_revenue) OVER (ORDER BY year_month) AS previous_revenue,
    current_revenue - LAG(current_revenue) OVER (ORDER BY year_month) AS revenue_difference
FROM monthly_revenue
ORDER BY year_month;


